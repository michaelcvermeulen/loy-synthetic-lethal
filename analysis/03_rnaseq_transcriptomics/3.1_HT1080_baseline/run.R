# Deliberately rebuild every stage: no timestamp or .done shortcuts can retain stale results.
options(warn = 1, stringsAsFactors = FALSE)
script <- sub('^--file=', '', grep('^--file=', commandArgs(FALSE), value = TRUE)[1])
ROOT <- dirname(normalizePath(script, winslash = '/', mustWork = TRUE))
setwd(ROOT)
REPO <- normalizePath('../../..', winslash = '/', mustWork = TRUE)
for (d in c('outputs/tables', 'outputs/models', 'outputs/figures', 'outputs/source_data',
             'outputs/captions', 'outputs/report', 'provenance', 'report', 'tests'))
  dir.create(d, recursive = TRUE, showWarnings = FALSE)
invisible(lapply(sort(list.files('R', pattern = '\\.R$', full.names = TRUE)), source))
cfg <- yaml::read_yaml('config/analysis.yml'); set.seed(cfg$seed)
data.table::setDTthreads(2)
suppressPackageStartupMessages(library(SummarizedExperiment))
assert(file.exists('resources/manifest.csv'), 'Run prepare_resources.R before run.R')
frozen <- data.table::fread('resources/manifest.csv')
assert(all(vapply(frozen$path, hash_file, character(1)) == frozen$sha256), 'Frozen resource hashes changed')
args <- commandArgs(trailingOnly = TRUE)
x <- stage('01_ingest', function() ingest(cfg, REPO))
e <- stage('02_expression', function() expression_analysis(x, cfg))
stage('batch_aware_DE', function() batch_aware_de(x, e))
assert(system2('python', 'plot_batch_aware_de.py') == 0, 'Batch-aware DE figure render failed')
if ('--core-only' %in% args) quit(status = 0)
p <- stage('03_pathways_regulators', function() pathway_analysis(x, e, cfg))
d <- stage('04_dosage_repeatability', function() dosage_analysis(x, e, p, cfg))
stage('04_ZMYND8_followup', function() zmynd8_followup(x, e, p, cfg))
stage('04_chromatin_followup', function() chromatin_followup(x, e, p, cfg))
stage('04_HDAC12_gene_drivers', function() hdac12_followup(x, e, p))
external_resources <- data.table::fread('resources/hdac12_external/GSE193885/manifest.csv')
assert(all(vapply(external_resources$path, hash_file, character(1)) == external_resources$sha256),
  'Frozen external resource hashes changed')
external <- stage('04_HDACEXT_source_models', function() hdac_external_source(e))
hdac_external_ms_audit(external)
stage('04_HDACEXT_comparison', function() hdac_external_compare(external, x, e, p))
epigenetic_resources <- data.table::fread('resources/epigenetic_deep_dive/manifest.csv')
assert(all(vapply(epigenetic_resources$path, hash_file, character(1)) == epigenetic_resources$sha256),
  'Frozen epigenetic resources changed')
stage('04_epigenetic_deep_dive', function() epigenetic_deep_dive(x, e, p))
stage('05_chromatin_GSEA_curves', function() chromatin_gsea_curve_data(p, e,
  yaml::read_yaml('config/chromatin_GSEA_curves.yml')))
stage('05_figures', function() make_figures(x, e, p, d, cfg))
finalize_run(x, e, p, d, cfg, REPO)
