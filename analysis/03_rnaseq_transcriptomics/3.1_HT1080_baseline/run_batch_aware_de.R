options(warn=1,stringsAsFactors=FALSE)
script <- sub("^--file=","",grep("^--file=",commandArgs(FALSE),value=TRUE)[1])
setwd(dirname(normalizePath(script,winslash="/",mustWork=TRUE)))
source("R/00_common.R");source("R/03_enrichment_helpers.R");source("R/02_batch_aware_de.R")
data.table::setDTthreads(2)
paths <- c("outputs/models/01_ingest.rds","outputs/models/02_expression.rds","outputs/tables/HT1080_LOY_vs_sgCTRL_primary_effects.csv","outputs/tables/symbol_mapping_representatives.csv","config/analysis.yml")
if(file.exists("config/network_modules.json")) paths <- c(paths,"config/network_modules.json")
hashes <- data.frame(path=paths,sha256=vapply(paths,hash_file,character(1)))
frozen <- "provenance/batchDE_input_hashes.csv"
if(file.exists(frozen)) {
 old <- data.table::fread(frozen)
 assert(identical(hashes$path,old$path) && identical(hashes$sha256,old$sha256),"Frozen input changed")
} else data.table::fwrite(hashes,frozen)
x <- readRDS(paths[1]); e <- readRDS(paths[2])
set.seed(42)
z <- batch_aware_de(x,e)
saveRDS(z,"outputs/models/batch_aware_DE.rds")
assert(identical(vapply(paths,hash_file,character(1)),setNames(hashes$sha256,paths)),"Original inputs changed")
writeLines(c("Scientific checks passed: original integer counts; same 25526 genes and 12 samples; full-rank designs; positive voom weights; finite P/FDR; BH verified; equal-period contrast verified; original inputs unchanged.",capture.output(z$summary),capture.output(sessionInfo())),"provenance/batchDE_validation.txt")
print(z$summary)
