bins <- readRDS("../t2t_bins_100kb.rds")
df <- bins@data
cat("Total bins:", nrow(df), "\n")
cat("Median bases (% non-N):", median(df$bases), "\n")
cat("Median mappability:", median(df$mappability), "\n")
cat("Median blacklist:", median(df$blacklist), "\n\n")
cat("Mappability quantiles:\n")
print(quantile(df$mappability, c(0.05, 0.25, 0.5, 0.75, 0.95)))
cat("\nBlacklist quantiles:\n")
print(quantile(df$blacklist, c(0.5, 0.75, 0.9, 0.95, 0.99)))
cat("\nBins passing each filter:\n")
cat("bases > 90:", sum(df$bases > 90), "\n")
cat("mappability >= 50:", sum(df$mappability >= 50), "\n")
cat("mappability >= 25:", sum(df$mappability >= 25), "\n")
cat("mappability >= 10:", sum(df$mappability >= 10), "\n")
cat("blacklist < 10:", sum(df$blacklist < 10), "\n")
cat("blacklist < 25:", sum(df$blacklist < 25), "\n")
cat("blacklist < 50:", sum(df$blacklist < 50), "\n\n")
cat("Combined filters (current = bases>90 & map>=50 & bl<10):", sum(df$bases > 90 & df$mappability >= 50 & df$blacklist < 10), "\n")
cat("Relaxed (bases>50 & map>=25 & bl<50):", sum(df$bases > 50 & df$mappability >= 25 & df$blacklist < 50), "\n")
cat("Just bases>50:", sum(df$bases > 50), "\n")
